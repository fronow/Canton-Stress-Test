// Generates amulet-accept.json: the SECOND step of a two-step Canton Coin
// transfer, the receiver accepting an offer.
//
// amulet-transfer.json measures the first step: with no preapproval, the
// sender's TransferFactory_Transfer locks the amulet and creates an
// AmuletTransferInstruction. Here setup makes one such offer per measured
// operation, and each measured operation is the receiver's
// TransferInstruction_Accept on the next unused offer. Offer + accept together
// are the cost of a transfer to a receiver without a preapproval.
const fs = require("node:fs");
const path = require("node:path");

const base = JSON.parse(fs.readFileSync(path.join(__dirname, "amulet-transfer.json"), "utf8"));
const w = structuredClone(base);
w._comment = [
  "Canton Coin (Amulet) two-step transfer, second step: the receiver accepts the offer.",
  "Generated by gen-amulet-accept.cjs.",
];

const holdings = w.setup.find((s) => s.id === "holdings");
const offer = structuredClone(w.operations[0].op);
offer.args.transfer.inputHoldingCids = ["$ref:holdings[$i]"];
w.setup.push({
  _comment: "One offer per holding: the measured transfer of amulet-transfer.json, run in setup.",
  id: "offers",
  count: holdings.count,
  actAs: ["$p0"],
  readAs: ["$role:admin"],
  bind: "AmuletTransferInstruction",
  op: offer,
});

w.operations = [
  {
    weight: 1,
    _comment: "The receiver accepts the next unused offer.",
    op: {
      kind: "exercise",
      template: "#splice-api-token-transfer-instruction-v1:Splice.Api.Token.TransferInstructionV1:TransferInstruction",
      contract: "$ref:offers[seq]",
      choice: "TransferInstruction_Accept",
      args: {
        extraArgs: {
          context: { values: { "external-party-config-state": { tag: "AV_ContractId", value: "$ref:config" } } },
          meta: { values: {} },
        },
      },
    },
    // The locked amulet behind the offer is signed by the DSO and the sender; a
    // wallet gets it from the registry as a disclosed contract. Reading as the
    // sender gives the receiver the same view without changing the transaction.
    submit: { actAs: ["$p1"], readAs: ["$p0"] },
  },
];

fs.writeFileSync(path.join(__dirname, "amulet-accept.json"), JSON.stringify(w, null, 2) + "\n");
console.log("wrote amulet-accept.json");
