// Generates amulet-preapproved.json: a Canton Coin (Amulet) transfer that
// COMPLETES in one transaction, the way most MainNet transfers do.
//
// amulet-transfer.json (gen-amulet.cjs) passes no preapproval, so
// ExternalPartyAmuletRules takes the two-step path: it locks the sender's
// amulet and creates an AmuletTransferInstruction for the receiver to accept.
// That is the OFFER, not a completed transfer.
//
// This workload adds what a MainNet wallet passes (a sample of 200 MainNet
// transactions on 2026-10-20: 35% were single TransferFactory_Transfer calls,
// all of this shape):
//   - the receiver's TransferPreapproval (signed by receiver, provider, DSO),
//     so the factory exercises TransferPreapproval_SendV2 and the transfer
//     completes;
//   - the provider's FeaturedAppRight, so a FeaturedAppActivityMarker is created
//     (rewardCalculationVersion = None means featured-app markers are in use);
//   - the open-round and amulet-rules context keys that MainNet's registry
//     returns. The external-party path does not read them, but they travel in
//     the choice argument, so they are billed. They point at the config state
//     here: same size as a real contract id.
// The holdings-change event log (two EventLog_HoldingsChange exercises) needs
// nothing extra: on this path it is always written.
const fs = require("node:fs");
const path = require("node:path");

const base = JSON.parse(fs.readFileSync(path.join(__dirname, "amulet-transfer.json"), "utf8"));
const w = structuredClone(base);
w._comment = [
  "Canton Coin (Amulet) transfer completed through the receiver's TransferPreapproval,",
  "with a featured-app right, as MainNet wallets submit it. Generated by gen-amulet-preapproved.cjs.",
];

// The preapproval's provider: the app or validator that manages it for the
// receiver. On MainNet this is usually the receiver's validator party.
const provider = "$p2";

w.setup.push(
  {
    _comment: "The provider's FeaturedAppRight (signed by the DSO), read from the transfer's context.",
    id: "featured",
    disclose: true,
    actAs: ["$role:admin"],
    op: {
      kind: "create",
      template: "#splice-amulet:Splice.Amulet:FeaturedAppRight",
      args: { dso: "$role:admin", provider },
    },
  },
  {
    _comment: "The receiver's TransferPreapproval, signed by the receiver, the provider and the DSO.",
    id: "preapproval",
    disclose: true,
    actAs: ["$role:admin", "$p1", provider],
    op: {
      kind: "create",
      template: "#splice-amulet:Splice.AmuletRules:TransferPreapproval",
      args: {
        dso: "$role:admin",
        receiver: "$p1",
        provider,
        validFrom: "$now-60s",
        lastRenewedAt: "$now-60s",
        expiresAt: "$now+24h",
      },
    },
  },
);

const cid = (ref) => ({ tag: "AV_ContractId", value: ref });
w.operations[0].op.args.extraArgs.context.values = {
  "transfer-preapproval": cid("$ref:preapproval"),
  "open-round": cid("$ref:config"),
  "external-party-config-state": cid("$ref:config"),
  "amulet-rules": cid("$ref:config"),
  "featured-app-right": cid("$ref:featured"),
};

fs.writeFileSync(path.join(__dirname, "amulet-preapproved.json"), JSON.stringify(w, null, 2) + "\n");
console.log("wrote amulet-preapproved.json");
