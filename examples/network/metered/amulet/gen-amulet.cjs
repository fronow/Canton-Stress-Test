// Generates amulet-transfer.json: a Canton Coin (Amulet) transfer through the
// standard TransferFactory_Transfer, built from the library workload.
//
// What Amulet needs beyond any other registry: the transfer reads ONE entry
// from its choice context, "external-party-config-state", a contract signed by
// the DSO that carries the transfer configuration (ExternalPartyAmuletRules.daml,
// getExternalPartyConfigStateFromChoiceContext). The planner cannot synthesise
// it because TransferConfigV2 is a parameterised record, so it is written here
// by hand, created in setup, disclosed to the sender, and passed in the context.
//
// Fees and expiry are zeroed (holding fee rate 0.0), so holdings never expire
// during a run and the measured bytes are the transfer's, not fee bookkeeping.
const fs = require("node:fs");
const path = require("node:path");
const lib = JSON.parse(fs.readFileSync(path.resolve(__dirname, "../../../../workloads/token-standard-transfer.json"), "utf8"));

const params = {
  parties: 6,
  holdings: 60,
  instrumentId: "Amulet",
  transferAmount: "1.0",
  factoryTemplate: "#splice-amulet:Splice.ExternalPartyAmuletRules:ExternalPartyAmuletRules",
  factoryArgs: { dso: "$role:admin" },
  holdingTemplate: "#splice-amulet:Splice.Amulet:Amulet",
  holdingActAs: ["$role:admin", "$p0"],
  holdingArgs: {
    dso: "$role:admin",
    owner: "$p0",
    amount: { initialAmount: "1000.0", createdAt: { number: 0 }, ratePerRound: { rate: "0.0" } },
  },
};
const subst = (v) =>
  typeof v === "string" && v.startsWith("$param:") ? params[v.slice(7)] ?? v
  : Array.isArray(v) ? v.map(subst)
  : v && typeof v === "object" ? Object.fromEntries(Object.entries(v).map(([k, x]) => [k, subst(x)]))
  : v;
const w = subst(lib);

w._comment = [
  "Canton Coin (Amulet) transfer via TransferFactory_Transfer. Generated by gen-amulet.cjs.",
  "Needs splice-amulet DAR uploaded; see METERED.md.",
];
w.setup.splice(1, 0, {
  _comment: "The DSO's ExternalPartyConfigState, which every Amulet transfer reads from its context.",
  id: "config",
  disclose: true,
  actAs: ["$role:admin"],
  op: {
    kind: "create",
    template: "#splice-amulet:Splice.ExternalPartyConfigState:ExternalPartyConfigState",
    args: {
      dso: "$role:admin",
      holdingFeesOpenRoundNumber: { number: 0 },
      amuletPrice: "1.0",
      transferConfig: {
        holdingFee: { rate: "0.0" },
        maxNumInputs: 100,
        maxNumOutputs: 100,
        maxNumLockHolders: 50,
        tokenStandardMaxTTL: null,
      },
      targetArchiveAfter: "$now+1h",
      rewardCalculationVersion: null,
      amuletSwitchOverTimes: null,
    },
  },
});
w.operations[0].op.args.extraArgs.context.values = {
  "external-party-config-state": { tag: "AV_ContractId", value: "$ref:config" },
};
fs.writeFileSync(path.join(__dirname, "amulet-transfer.json"), JSON.stringify(w, null, 2) + "\n");
console.log("wrote amulet-transfer.json");
