// Generate an N-participant Canton network config, and a console config that
// attaches to it.
//
//   node gen-network.cjs 8        → participants-8.conf + remote-8.conf
//
// Same layout as two-participants.conf / four-participants.conf: one sequencer,
// one mediator, N participants, all in memory. Participant i (1-based) uses
//   ledger API 5000 + 10*i + 1, admin API 5000 + 10*i + 2, JSON API 7000 + 10*i + 1
// so participants 1-4 keep the ports of four-participants.conf. Works up to 99.
//
// Boot it metered with the same bootstrap as the smaller networks:
//   java -jar canton.jar daemon -c participants-8.conf --bootstrap bootstrap-metered.canton
// (bootstrap-metered.canton connects and funds every participant it finds.)
//
// Memory: each in-memory participant needs roughly 0.4-0.6 GB of heap; give the
// JVM about 0.6 GB per participant (-Xmx).

const fs = require("node:fs");
const path = require("node:path");

const n = Number(process.argv[2]);
if (!Number.isInteger(n) || n < 1 || n > 99) {
  console.error("usage: node gen-network.cjs <participants 1-99>");
  process.exit(2);
}
const port = (i, k) => 5000 + 10 * i + k;
const http = (i) => 7000 + 10 * i + 1;
const ids = Array.from({ length: n }, (_, k) => k + 1);

const participants = ids
  .map(
    (i) => `    participant${i} {
      storage.type = memory
      admin-api.port = ${port(i, 2)}
      ledger-api.port = ${port(i, 1)}
      http-ledger-api {
        server.port = ${http(i)}
      }
    }`,
  )
  .join("\n");

const conf = `// ${n} participants, one sequencer and one mediator on one synchronizer.
// Generated by gen-network.cjs; boot with bootstrap-metered.canton for traffic
// control. Everything is in memory: a test rig, not a deployment.

canton {
  parameters {
    non-standard-config = yes
  }

  participants {
${participants}
  }

  sequencers {
    sequencer1 {
      storage.type = memory
      public-api.port = 5001
      admin-api.port = 5002
    }
  }

  mediators {
    mediator1 {
      storage.type = memory
      admin-api.port = 5003
    }
  }
}
`;

const remote = `// A console that ATTACHES to the running participants-${n}.conf network.
// Generated by gen-network.cjs.

canton {
  remote-mediators {
    mediator1 { admin-api.port = 5003 }
  }
  remote-sequencers {
    sequencer1 {
      public-api {
        address = "localhost"
        port = 5001
      }
      admin-api.port = 5002
    }
  }
  remote-participants {
${ids.map((i) => `    participant${i} {\n      admin-api.port = ${port(i, 2)}\n      ledger-api.port = ${port(i, 1)}\n    }`).join("\n")}
  }
}
`;

fs.writeFileSync(path.join(__dirname, `participants-${n}.conf`), conf);
fs.writeFileSync(path.join(__dirname, `remote-${n}.conf`), remote);
console.log(`wrote participants-${n}.conf and remote-${n}.conf`);
console.log(`JSON APIs: ${ids.map(http).join(", ")}`);
